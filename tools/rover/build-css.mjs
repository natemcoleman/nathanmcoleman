// Builds static/rover/css/tailwind.css from the classes used in the game's HTML and JS.
// Run after adding or changing Tailwind classes:   npm run rover:css
// Needs (once):   npm i --no-save tailwindcss@4 esbuild
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const ROVER = path.join(ROOT, 'static', 'rover');
const require = createRequire(import.meta.url);
const searchPaths = [ROOT, ...(process.env.ROVER_NODE_PATHS || '').split(path.delimiter).filter(Boolean)];

async function load(name, sub = '') {
  try {
    const pkgDir = path.dirname(require.resolve(`${name}/package.json`, { paths: searchPaths }));
    return { dir: pkgDir, mod: await import(pathToFileURL(require.resolve(name + sub, { paths: searchPaths })).href) };
  } catch {
    console.error(`Missing "${name}". Install the build tools once with:\n  npm i --no-save tailwindcss@4 esbuild`);
    process.exit(1);
  }
}
const tw = await load('tailwindcss');
const twCompile = tw.mod.compile || tw.mod.default.compile;
const esbuildMod = (await load('esbuild')).mod;
const esbuild = esbuildMod.transform ? esbuildMod : esbuildMod.default;

// Every word-like token in the page and scripts is a candidate; Tailwind ignores the ones that aren't classes.
const sources = [path.join(ROVER, 'index.html'), ...fs.readdirSync(path.join(ROVER, 'js')).map((f) => path.join(ROVER, 'js', f))];
const candidates = new Set();
for (const f of sources) {
  for (const t of fs.readFileSync(f, 'utf8').split(/[\s"'`<>=;{}(),\\]+/)) if (t && t.length < 100) candidates.add(t);
}

// Tailwind v4, tuned to match the v3 look the game was designed with.
const input = `
@import "tailwindcss";
@theme {
  --radius-sm: 0.125rem;  /* v3 rounded-sm */
  --blur-sm: 4px;         /* v3 backdrop-blur-sm */
}
@layer base {
  *, ::after, ::before, ::backdrop, ::file-selector-button { border-color: var(--color-gray-200, currentColor); }
  button:not(:disabled), [role="button"]:not(:disabled) { cursor: pointer; }
  input::placeholder, textarea::placeholder { color: var(--color-gray-400); }
}
`;
const compiler = await twCompile(input, {
  base: tw.dir,
  loadStylesheet: async (id, base) => {
    const rel = id === 'tailwindcss' ? 'index.css' : id.replace(/^tailwindcss\//, '');
    const file = id.startsWith('tailwindcss') ? path.join(tw.dir, rel.endsWith('.css') ? rel : rel + '.css') : path.resolve(base, id);
    return { path: file, base: path.dirname(file), content: fs.readFileSync(file, 'utf8') };
  },
});
let css = compiler.build([...candidates]);

// Unwrap cascade layers so game.css and the utilities compete by specificity and order, as they did with v3.
css = css.replace(/@layer [\w\s,-]+;/g, '');
function unwrapLayers(src) {
  let out = '', i = 0;
  const re = /@layer\s+[\w-]+\s*\{/g;
  let m;
  while ((m = re.exec(src))) {
    out += src.slice(i, m.index);
    let depth = 1, j = re.lastIndex;
    for (; j < src.length && depth; j++) { if (src[j] === '{') depth++; else if (src[j] === '}') depth--; }
    out += unwrapLayers(src.slice(re.lastIndex, j - 1));
    i = j; re.lastIndex = j;
  }
  return out + src.slice(i);
}
css = unwrapLayers(css);

// Lower newer syntax (nesting, range media queries) for older phone browsers, and minify.
const { code } = await esbuild.transform(css, { loader: 'css', minify: true, target: ['chrome111', 'safari15.4', 'firefox113', 'edge111'] });
fs.mkdirSync(path.join(ROVER, 'css'), { recursive: true });
fs.writeFileSync(path.join(ROVER, 'css', 'tailwind.css'), '/* Generated by tools/rover/build-css.mjs — do not edit */\n' + code);
console.log(`tailwind.css: ${(code.length / 1024).toFixed(1)} KB from ${sources.length} files`);
